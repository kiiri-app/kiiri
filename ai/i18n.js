function normalize(lang) {
  const l = String(lang || "").toLowerCase().slice(0, 2);
  return LANGS.includes(l) ? l : null;
}

function setLanguage(lang) {
  current = normalize(lang) || "en";
  return current;
}

function getLanguage() {
  return current;
}

// t(key, lang, ...args): lang falls back to the current UI language.
function t(key, lang, ...args) {
  const l = normalize(lang) || current;
  let v = STRINGS[l][key];
  if (v === undefined) v = STRINGS.en[key];
  if (v === undefined) return key;
  return typeof v === "function" ? v(...args) : v;
}

// msg(key, ...args): t() in the current UI language.
function msg(key, ...args) {
  return t(key, current, ...args);
}

module.exports = { t, msg, setLanguage, getLanguage, LANGS, STRINGS };
